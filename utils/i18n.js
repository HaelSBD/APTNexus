const DICT = { en: EN, ms: MS, zh: ZH };

export function t(lang, key, vars) {
  const table = DICT[lang] || EN;
  let out = table[key] || EN[key] || key;
  if (vars && typeof out === "string") {
    Object.entries(vars).forEach(([name, value]) => {
      out = out.split(`{${name}}`).join(String(value));
    });
  }
  return out;
}

export function useT() {
  const { settings } = useSettings();
  const lang = settings?.language || "en";
  return (key, vars) => t(lang, key, vars);
}

export function translateRole(tFn, role) {
  const value = String(role || "").toLowerCase();
  if (value === "superadmin") return tFn("roleSuper");
  if (value === "admin") return tFn("roleAdmin");
  return tFn("roleSecurity");
}
